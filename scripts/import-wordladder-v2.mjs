// Offline importer; never invoked by the app build. Requires Python 3.7+ with SQLite 3.33+.
// Usage: node scripts/import-wordladder-v2.mjs /path/to/source.tar.gz [python3]
// Download the pinned archive and see the exact policy in DICTIONARY-LICENSE.txt.
import { createHash } from 'node:crypto';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const commit = '7e99edab8e32f9f9ea2b15f249ca8d4d67237410';
const archiveHash = '770dd3e42d20b47bb2dd87d150db4ee5472841a7f062876592f67840f5a0b902';
const archiveUrl = `https://codeload.github.com/en-wl/wordlist/tar.gz/${commit}`;
const root = new URL('../', import.meta.url);
const noticeUrl = new URL('src/lib/games/wordladder/DICTIONARY-LICENSE.txt', root);
const section = '\n\nWord Ladder vocabulary and generator v2\n';
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const wordHash = (words) => sha256(`${words.join('\n')}\n`);
const [archivePath, python = 'python3', ...extra] = process.argv.slice(2);
if (!archivePath || extra.length) {
  throw new Error('Usage: node scripts/import-wordladder-v2.mjs /path/to/source.tar.gz [python3]');
}
if (sha256(await readFile(archivePath)) !== archiveHash) {
  throw new Error(`Source archive SHA-256 mismatch; expected ${archiveHash} from ${archiveUrl}`);
}
const temporary = await mkdtemp(join(tmpdir(), 'wordladder-v2-'));
function run(command, args, cwd) {
  const result = spawnSync(command, args, {
    cwd,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    env: { ...process.env, PYTHONUTF8: '1', PYTHONDONTWRITEBYTECODE: '1', SCOWL_OPTS: '', SCOWL_DEBUG_SQL: 'False' }
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} failed (${result.status}):\n${result.stderr}`);
  if (result.stderr) process.stderr.write(result.stderr);
  return result.stdout;
}
try {
  run('tar', ['-xzf', resolve(archivePath), '-C', temporary], temporary);
  const source = join(temporary, `wordlist-${commit}`);
  // This is the upstream Makefile's database-creation command, not a reimplementation.
  run(python, ['combine.py', 'create-db', 'scowl.db'], source);
  const extracted = JSON.parse(run(python, ['-c', `
import json, re
import libscowl
conn = libscowl.openDB('scowl.db')
def extract(size, spellings, variant):
    words = libscowl.getWords(
        conn, size, spellings, variant,
        categories=libscowl.Include(''),
        poses=libscowl.Exclude('abbr', 's', 'pre', 'suf', 'wp', 'we', 'x'),
        posClasses=libscowl.Exclude('person', 'surname', 'place', 'name', 'name?',
                                   'upper', 'upper?', 'trademark', 'abbr', 'abbr?'),
        deaccent=True, dot=False, apostrophe=False)
    return sorted({word.upper() for word in words if re.fullmatch('[a-z]{4}', word)})
print(json.dumps({'playable': extract(80, ['A', 'B', 'Z', 'C', 'D'], 6),
                  'endpoints': extract(35, ['A', 'B', 'Z'], 1)}))
conn.close()
`], source));
  const { playable, endpoints } = extracted;
  const playableSet = new Set(playable);
  if (!endpoints.every((word) => playableSet.has(word))) throw new Error('Endpoints are not a playable subset');
  for (const word of ['ORCA', 'MISO', 'CHAI', 'UDON', 'ROTI', 'CAFE', 'EPEE']) {
    if (!playableSet.has(word)) throw new Error(`Expected pinned-source move missing: ${word}`);
  }
  const array = (name, words) => {
    const lines = [];
    for (let index = 0; index < words.length; index += 10) {
      lines.push(`  ${words.slice(index, index + 10).map((word) => `'${word}'`).join(', ')}${index + 10 < words.length ? ',' : ''}`);
    }
    return `export const ${name}: readonly string[] = Object.freeze([\n${lines.join('\n')}\n]);`;
  };
  const module = `// Copyright 2000-2026 by Kevin Atkinson; Copyright 2016 by Benjamin Titze.
// Copyright (c) J Ross Beresford 1993-1999. All Rights Reserved.
// WordNet 1.6 Copyright 1997 by Princeton University. All rights reserved.
// Modified ESDB/SCOWLv2 rel-2026.02.25 extract. Generated by scripts/import-wordladder-v2.mjs.
// See DICTIONARY-LICENSE.txt for pinned source, exact policy, hashes, and full notices.
// PLAYABLE_WORDS: ${playable.length}; SHA-256 (one word + LF): ${wordHash(playable)}.
// ENDPOINT_WORDS: ${endpoints.length}; SHA-256 (one word + LF): ${wordHash(endpoints)}.
${array('PLAYABLE_WORDS', playable)}

${array('ENDPOINT_WORDS', endpoints)}
`;
  const originalNotice = (await readFile(noticeUrl, 'utf8')).split(section)[0].trimEnd();
  const copyright = await readFile(join(source, 'Copyright'), 'utf8');
  const notice = `${originalNotice}${section}======================================

Source: maintained ESDB / SCOWLv2, rel-2026.02.25
Repository: https://github.com/en-wl/wordlist
Pinned commit: ${commit}
Archive: ${archiveUrl}
Archive SHA-256: ${archiveHash}
data/scowl-pre.txt SHA-256: ${sha256(await readFile(join(source, 'data/scowl-pre.txt')))}
combine.py SHA-256: ${sha256(await readFile(join(source, 'combine.py')))}
Copyright SHA-256: ${sha256(copyright)}

This is a modified generated word list, not the upstream database. No network
requests or Python/SQLite dependencies are used by the application or build.
Only this explicit offline import uses the upstream Python/SQLite tooling.
The v1 list, move-only ORCA correction, graph, and seed mapping remain frozen.

Reproduction (Python 3.7+ with SQLite 3.33+; Node and tar):
  curl -fLsS '${archiveUrl}' -o /tmp/wordladder-esdb.tar.gz
  node scripts/import-wordladder-v2.mjs /tmp/wordladder-esdb.tar.gz python3
The importer verifies the archive hash before extracting it to a temporary
folder. It executes upstream 'python3 combine.py create-db scowl.db' (the
Makefile recipe), then calls the supported libscowl.getWords API. It does not
parse SCOWL text itself or substitute the older SCOWLv1 word lists. The source
archive hash pins every input, schema, and extraction-tool implementation.

Both pools use the ordinary category only (categories=Include('')). Exclude
base POS abbr, s, pre, suf, wp, we, x (abbreviations, contractions, affixes,
compound fragments and nonwords). Exclude POS classes person, surname, place,
name, name?, upper, upper?, trademark, abbr, abbr?. After the official deaccent
mapping, require exactly four lowercase ASCII a-z characters BEFORE uppercasing
and deduplicating. Thus name-only/uppercase entries do not become ordinary
words; an independently classified lowercase ordinary sense is still accepted.
Dots and apostrophes are forbidden rather than stripped; the upstream default
word filter also excludes spaces, hyphens, digits and special symbols. Accents
are folded only by libscowl.deaccent (e.g. cafe from cafe/café and epee from
épée); ligatures or punctuation are not silently removed. Offensive/vulgar
usage notes are not filtered. All arrays are unique and sorted by ASCII.

Moves: size <=80, spellings A/B/Z/C/D (American, British -ise and -ize,
Canadian, Australian), and ESDB variant_level <=6. The upstream API includes
unmarked '_' spellings, non-regional entries, the matching US/GB/CA/AU regions,
and resolves lemma/derived spelling inheritance via the database views.
ESDB levels: 0 non-variant, 1 include, 2 equal, 3 disagreement, 4 common,
5 legacy/unspecified variant, 6 acceptable. All of these are accepted; levels
7 uncommon, 8 archaic and 9 invalid are excluded. These are NOT SCOWLv1's
legacy_level numbers. Size 80 is upstream's current-valid word-game tier;
size 85 (including words no longer in modern use) is excluded.

This maintained v2 extract is smaller than a broad SCOWLv1 word-game extract.
SCOWLv2 reprocesses the sources and corrects derived forms and variants; the
ordinary-only classification and accepted-variant filters also differ. It is
not expected to reproduce historical SCOWLv1 size-80 word counts, and no
legacy vocabulary has been added to force those counts to match.

Endpoints: size <=35, spellings A/B/Z, ESDB variant_level <=1 (the standard
default spellings, including upstream's specially included coequal forms),
with the same category/POS/casing/deaccent filters. This is a subset of the
move pool. ENDPOINT_WORDS is the familiar candidate pool, not a graph: the
v2 engine further restricts endpoints to the largest connected component of
the full PLAYABLE_WORDS graph and calculates shortest paths through that full
move graph. No manual additions or removals occur in either v2 pool.
ORCA, MISO, CHAI, UDON, ROTI, CAFE and EPEE are present in the imported move pool.
Their ordinary-noun source entries are unmarked spelling '_' / variant 0:
orca, miso, chai, udon and roti first appear at size 60; café at size 35;
épée at size 50. The unaccented 'cafe' entry itself is size 35 / variant 5,
but CAFE is also an endpoint through the standard variant-0 'café' alias.

PLAYABLE_WORDS: ${playable.length} words.
Newline-terminated ASCII-sorted uppercase word SHA-256:
${wordHash(playable)}
ENDPOINT_WORDS: ${endpoints.length} words before connected-component filtering.
Newline-terminated ASCII-sorted uppercase word SHA-256:
${wordHash(endpoints)}
Generated words-v2.ts SHA-256:
${sha256(module)}

Frozen generator v2: use the same exact-seed UTF-16LE FNV-1a and xorshift32
operations documented for v1. Build adjacency from PLAYABLE_WORDS, retaining
all single-position substitutions, and find its largest connected component.
Visit words in ASCII order; equal-size component ties retain the first.
Filter ENDPOINT_WORDS to that component in ASCII order. The first xorshift
draw selects the start modulo the filtered endpoint count. BFS traverses all
playable neighbors, not just endpoint candidates. Eligible targets are the
filtered endpoints in ASCII order with distance >=4 and no letters in common
with the start. The second xorshift draw selects a target modulo that count.
Return the exact BFS distance as an informational reference. Graph caches do
not contain RNG state; only the requested version is constructed.


All pinned upstream Copyright notices follow verbatim, including Australian,
UKACD and WordNet notices (retained even when upstream says they may not apply):

${copyright.trimEnd()}
`;
  await writeFile(new URL('src/lib/games/wordladder/words-v2.ts', root), module);
  await writeFile(noticeUrl, notice);
  await writeFile(new URL('static/wordladder-word-list-license.txt', root), notice);
  console.log(`PLAYABLE_WORDS ${playable.length} ${wordHash(playable)}`);
  console.log(`ENDPOINT_WORDS ${endpoints.length} ${wordHash(endpoints)}`);
} finally {
  await rm(temporary, { recursive: true, force: true });
}
